function circ(cx,cy,r){return `M${cx-r} ${cy}a${r} ${r} 0 1 0 ${2*r} 0a${r} ${r} 0 1 0 ${-2*r} 0`}
function conv(tag,a){
 switch(tag){
  case 'path':return a.d;
  case 'circle':return circ(+a.cx,+a.cy,+a.r);
  case 'ellipse':return `M${+a.cx-+a.rx} ${a.cy}a${a.rx} ${a.ry} 0 1 0 ${2*a.rx} 0a${a.rx} ${a.ry} 0 1 0 ${-2*a.rx} 0`;
  case 'line':return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`;
  case 'polyline':return 'M'+a.points.trim().split(/\s+/).join('L');
  case 'polygon':return 'M'+a.points.trim().split(/\s+/).join('L')+'Z';
  case 'rect':{const x=+a.x||0,y=+a.y||0,w=+a.width,h=+a.height,r=+(a.rx||0);
    if(!r)return `M${x} ${y}h${w}v${h}h${-w}Z`;
    return `M${x+r} ${y}h${w-2*r}a${r} ${r} 0 0 1 ${r} ${r}v${h-2*r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w-2*r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h-2*r)}a${r} ${r} 0 0 1 ${r} ${-r}Z`}
 }
 throw new Error(tag);
}
