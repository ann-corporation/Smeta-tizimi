/** Short-prefix entries must match a WORD START only; longer ones may match anywhere inside a word. */
const SOZ_BOSHI = new Set(['том', 'пол', 'сим', 'сув', 'чок', 'эшик', 'қум', 'тош', 'ортиқ', 'гача', 'лага', 'устун']);

const UZ = /[қўғҳ]/i;
export const uzbekMi = (matn: string | null | undefined) => UZ.test(matn ?? '');

/** Russian glossary words for an Uzbek-Cyrillic text; '' for non-Uzbek text or no hit. */
export function uzRuAlias(matn: string | null | undefined): string {
  if (!matn || !UZ.test(matn)) return '';
  const words = matn.toLowerCase().replace(/[^а-яёқўғҳ\s]+/g, ' ').split(/\s+/).filter(Boolean);
  const out = new Set<string>();
  for (const w of words) for (const [p, ru] of LUGAT) {
    const hit = SOZ_BOSHI.has(p) ? w.startsWith(p) : w.includes(p);
    if (hit) for (const r of ru.split(' ')) out.add(r);
  }
  return [...out].join(' ');
}
