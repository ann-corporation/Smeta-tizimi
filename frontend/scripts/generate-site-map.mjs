import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const app = fs.readFileSync(path.join(root, 'src/App.tsx'), 'utf8');
const shell = fs.readFileSync(path.join(root, 'src/admin/AdminShell.tsx'), 'utf8');
const sb = fs.readFileSync(path.join(root, 'functions/api/sb.ts'), 'utf8');
const sbWrite = fs.readFileSync(path.join(root, 'functions/api/sb-yoz.ts'), 'utf8');
const out = path.join(root, 'src/lib/sayt-xaritasi/generated.ts');

const unique = (xs) => [...new Set(xs)];
const menuRoutes = unique([...shell.matchAll(/yol:\s*'([^']+)'/g)].map((m) => m[1]));
const appRouteSegments = unique([...app.matchAll(/<Route\s+path="([^"]+)"/g)].map((m) => m[1]));
// Izohlar olib tashlanadi: ulardagi apostroflar ("ro'yxat") jadval nomi deb o'qilmasin.
const readBlock = (sb.match(/const RUXSAT_JADVALLAR[\s\S]*?\n\]\);/m)?.[0] ?? '').replace(/\/\*[\s\S]*?\*\//g, '');
const readTables = unique([...readBlock.matchAll(/'([^']+)'/g)].map((m) => m[1]));
const writeActions = [];
for (const m of sbWrite.matchAll(/^\s*([A-Za-z0-9_]+):\s*\{\s*rpc:\s*'([^']+)'\s*\}/gm)) {
  writeActions.push({ amal: m[1], rpc: m[2] });
}

const js = `/* AUTO-GENERATED by scripts/generate-site-map.mjs. Do not hand-edit. */\n` +
  `export const GENERATED_SITE_MAP = ${JSON.stringify({ generatedAt: 'source', menuRoutes, appRouteSegments, readTables, writeActions }, null, 2)} as const;\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
  if (current !== js) {
    console.error('Sayt xaritasi eskirgan. npm run site-map:generate ni ishga tushiring.');
    process.exit(1);
  }
} else {
  fs.writeFileSync(out, js);
  console.log(`Sayt xaritasi yaratildi: ${menuRoutes.length} menyu, ${readTables.length} read model, ${writeActions.length} write amal.`);
}
