-- T2-AGENT-CONTROL-PLANE-001
-- Source-only additive contract for bounded construction agents.
--
-- This is not an AI truth table. It records agent identity, guarded runs,
-- approval decisions and tool-call receipts. Business calculations remain in
-- the canonical domain commands/RPCs owned by their respective modules.

begin;

create table if not exists public.t2_agent_profile (
  kod text primary key,
  nom text not null,
  rol text not null,
  izoh text,
  permission_mode text not null default 'read_only'
    check (permission_mode in ('read_only','analyze','draft','command_prepare','human_approval_required')),
  allowed_commands jsonb not null default '[]'::jsonb
    check (jsonb_typeof(allowed_commands) = 'array'),
  allowed_tools jsonb not null default '[]'::jsonb
    check (jsonb_typeof(allowed_tools) = 'array'),
  default_scope text not null default 'company'
    check (default_scope in ('global','company','project','object')),
  holat text not null default 'active'
    check (holat in ('active','paused','deprecated')),
  versiya integer not null default 1 check (versiya > 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.t2_agent_run (
  id bigint generated by default as identity primary key,
  operation_id uuid not null unique,
  agent_kod text not null references public.t2_agent_profile(kod),
  actor_id bigint not null references public.t2_foydalanuvchi(id),
  kompaniya_id bigint references public.t2_kompaniya(id),
  loyiha_id bigint references public.t2_loyiha(id),
  obyekt_id bigint references public.t2_obyekt(id),
  command_kod text not null,
  holat text not null default 'queued'
    check (holat in ('queued','running','waiting_review','approval_required','applying','exporting','completed','failed','cancelled')),
  requires_approval boolean not null default true,
  input jsonb not null default '{}'::jsonb,
  result jsonb,
  error_code text,
  error_detail text,
  versiya integer not null default 1 check (versiya > 0),
  created_at timestamptz not null default now(),
  started_at timestamptz,
  finished_at timestamptz,
  updated_at timestamptz not null default now()
);

create index if not exists t2_agent_run_scope_ix
  on public.t2_agent_run (kompaniya_id, loyiha_id, obyekt_id, created_at desc);
create index if not exists t2_agent_run_state_ix
  on public.t2_agent_run (holat, updated_at desc);

create table if not exists public.t2_agent_approval (
  id bigint generated by default as identity primary key,
  run_id bigint not null unique references public.t2_agent_run(id) on delete cascade,
  holat text not null default 'pending'
    check (holat in ('pending','approved','rejected')),
  requested_at timestamptz not null default now(),
  decided_at timestamptz,
  decided_by bigint references public.t2_foydalanuvchi(id),
  sabab text,
  versiya integer not null default 1 check (versiya > 0)
);

create table if not exists public.t2_agent_tool_call (
  id bigint generated by default as identity primary key,
  run_id bigint not null references public.t2_agent_run(id) on delete cascade,
  sequence_no integer not null check (sequence_no > 0),
  operation_id uuid not null unique,
  actor_id bigint not null references public.t2_foydalanuvchi(id),
  tool_kod text not null,
  holat text not null default 'prepared'
    check (holat in ('prepared','executed','failed','blocked')),
  request jsonb not null default '{}'::jsonb,
  result jsonb,
  error_code text,
  created_at timestamptz not null default now(),
  unique (run_id, sequence_no)
);

create index if not exists t2_agent_tool_call_run_ix
  on public.t2_agent_tool_call (run_id, sequence_no);

create table if not exists public.t2_agent_command_log (
  operation_id uuid primary key,
  actor_id bigint not null references public.t2_foydalanuvchi(id),
  command text not null,
  natija jsonb not null,
  created_at timestamptz not null default now()
);

