-- 1. MUHIM TUZATISH: prodda _t2_tomon_rol_ok 'murojaat' amalini bilmaydi (20261212500000 uni tushirib qoldirgan -> else false), ya'ni
--    murojaat/predpisaniya yaratish, javob, qaror HAMMA uchun TOMON_ROL_YETARLI_EMAS beradi. Bu yerda tiklanadi + 'inspektor' (texnadzor) qo'shiladi.
-- 2. 'fakt' resursi faollashadi (faqat ko'rish): pudratchi bu obyekt uchun fakt hajmini ko'rishga ruxsat bersagina F2 tekshiruvi fakt bilan solishtiradi.
-- 3. t2_tomon_murojaat_javob_v1: predpisaniyaga javob FOTO-DALILSIZ qabul qilinmaydi (ijrochi shu raundda dalil biriktirishi shart).
-- 4. t2_tomon_hujjat_ol_v1: qabul qiluvchi (texnadzor/buyurtmachi) yuborilgan АОСР ning bog'langan lab protokol fayli va fotosini ochadi.
-- versiya: tarix (t2_qator o'qilmaydi; F2 qatorlari akt snapshotidan)

-- 1. Rol qoidasi
create or replace function public._t2_tomon_rol_ok(p_rol text, p_amal text) returns boolean
language sql immutable as $$
  select case p_amal
    when 'boshqarish' then p_rol in ('superadmin','admin','boss','rahbar','director')
    when 'taqdim'     then p_rol in ('superadmin','admin','boss','rahbar','director','pto')
    when 'qaror'      then p_rol in ('superadmin','admin','boss','rahbar','director','buyurtmachi','inspektor')
    when 'murojaat'   then p_rol in ('superadmin','admin','boss','rahbar','director','pto','prorab','buyurtmachi','inspektor','loyihachi')
    when 'izoh'       then p_rol not in ('kuzatuvchi')
    when 'korish'     then true
    else false end
$$;

-- 2. Resurs
update public.t2_tomon_resurs set faol = true,
       izoh = coalesce(izoh, 'Fakt hajmi (faqat ko''rish): texnadzor F2 ni fakt bilan solishtirishi uchun')
 where kalit = 'fakt' and not faol;

-- 3. Jadvallar
create table if not exists public.t2_tekshiruv (
  id bigint generated by default as identity primary key,
  kompaniya_id bigint not null references public.t2_kompaniya(id),
  aloqa_id bigint references public.t2_tomon_aloqa(id),
  obyekt_id bigint not null references public.t2_obyekt(id),
  sana date not null default current_date,
  ish_turi text not null check (length(btrim(ish_turi)) between 2 and 80),
  joy text check (joy is null or length(joy) <= 300),
  holat text not null default 'qoralama' check (holat in ('qoralama','yakunlandi','bekor')),
  natija text check (natija is null or natija in ('mos','mos_emas')),
  bandlar jsonb not null default '[]'::jsonb check (jsonb_typeof(bandlar) = 'array' and octet_length(bandlar::text) <= 65536),
  izoh text check (izoh is null or length(izoh) <= 2000),
  yaratdi_actor_id bigint,
  operation_id uuid,
  versiya integer not null default 1,
  yaratildi timestamptz not null default now(),
  yangilandi timestamptz not null default now(),
  yakunlandi_vaqti timestamptz
);
create unique index if not exists t2_tekshiruv_op_uq on public.t2_tekshiruv (kompaniya_id, operation_id) where operation_id is not null;
create index if not exists t2_tekshiruv_kompaniya_sana_idx on public.t2_tekshiruv (kompaniya_id, sana desc, id desc);
create index if not exists t2_tekshiruv_obyekt_idx on public.t2_tekshiruv (obyekt_id, sana desc);
alter table public.t2_tekshiruv enable row level security;
revoke all on table public.t2_tekshiruv from anon, authenticated;

alter table public.t2_tomon_murojaat
  add column if not exists tekshiruv_id bigint references public.t2_tekshiruv(id),
  add column if not exists band_kod text;
create index if not exists t2_tomon_murojaat_tekshiruv_idx on public.t2_tomon_murojaat (tekshiruv_id) where tekshiruv_id is not null;

create table if not exists public.t2_aosr_foto (
  id bigint generated by default as identity primary key,
  aosr_id bigint not null references public.t2_aosr(id),
  document_id bigint not null,
  kompaniya_id bigint not null references public.t2_kompaniya(id),
  actor_id bigint,
  yaratildi timestamptz not null default now(),
  unique (aosr_id, document_id)
);
alter table public.t2_aosr_foto enable row level security;
revoke all on table public.t2_aosr_foto from anon, authenticated;

-- 4. Predpisaniyaga javob: foto-dalil majburiy
create or replace function public.t2_tomon_murojaat_javob_v1(p_actor_id bigint, p_kompaniya_id bigint, p_id bigint, p_matn text, p_document_ids bigint[])
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare m public.t2_tomon_murojaat; v_son integer;
begin
  perform public._t2_tomon_azo(p_actor_id, p_kompaniya_id, 'murojaat');
  select * into m from public.t2_tomon_murojaat where id = p_id for update;
  if not found or m.ijrochi_kompaniya_id <> p_kompaniya_id or public._t2_tomon_murojaat_olish(p_id, p_kompaniya_id, true) is null then
    return jsonb_build_object('ok', false, 'code', 'TOPILMADI', 'error', 'Murojaat topilmadi');
  end if;
  if m.holat <> 'ochiq' then return jsonb_build_object('ok', false, 'code', 'HOLAT', 'error', 'Murojaat bajarishga ochiq emas'); end if;
  if length(btrim(coalesce(p_matn, ''))) < 3 then return jsonb_build_object('ok', false, 'code', 'JAVOB_KERAK', 'error', 'Nima qilinganini yozing'); end if;
  if m.turi = 'predpisaniya'
     and coalesce(array_length(p_document_ids, 1), 0) = 0
     and not exists (select 1 from public.t2_tomon_murojaat_hujjat h where h.murojaat_id = m.id and h.raund = m.raund and h.kompaniya_id = p_kompaniya_id) then
    return jsonb_build_object('ok', false, 'code', 'FOTO_KERAK', 'error', 'Predpisaniyani bajarganingizni foto bilan tasdiqlang (kamida bitta rasm)');
  end if;
  v_son := public._t2_tomon_dalil_biriktir(m, p_kompaniya_id, p_actor_id, p_document_ids);
  update public.t2_tomon_murojaat set holat = 'bajarildi', javob_actor_id = p_actor_id, javob_vaqti = now(), javob_matn = btrim(p_matn), versiya = versiya + 1, yangilandi = now() where id = m.id;
  insert into public.t2_tomon_hodisa (aloqa_id, murojaat_id, kompaniya_id, actor_id, tur, matn, meta) values (m.aloqa_id, m.id, p_kompaniya_id, p_actor_id, 'murojaat_javob', btrim(p_matn), jsonb_build_object('dalil_soni', v_son, 'raund', m.raund));
  return jsonb_build_object('ok', true, 'id', m.id, 'holat', 'bajarildi', 'dalil_soni', v_son);
end $$;

-- 5. Hujjat olish: + yuborilgan АОСР ning lab protokol fayli va fotosi (qabul qiluvchi uchun)
create or replace function public.t2_tomon_hujjat_ol_v1(p_actor_id bigint, p_document_id bigint)
returns jsonb language plpgsql stable security definer set search_path = public, pg_temp as $$
declare v_egasi bigint; d public.t2_document_registry;
begin
  if p_actor_id is null or p_actor_id <= 0 or p_document_id is null or p_document_id <= 0 then return jsonb_build_object('ok', false, 'code', 'DOCUMENT_FORBIDDEN'); end if;
  select t.taqdim_etuvchi_kompaniya_id into v_egasi
    from public.t2_tomon_taqdim t join public.t2_tomon_aloqa a on a.id = t.aloqa_id and a.holat = 'faol'
   where t.manba_jadval = 't2_document_registry' and t.manba_id = p_document_id and t.holat in ('yuborilgan','ko_rilmoqda','qabul')
     and exists (select 1 from public.t2_azolik z where z.foydalanuvchi_id = p_actor_id and z.kompaniya_id = t.qabul_qiluvchi_kompaniya_id and z.holat = 'faol')
   order by t.id desc limit 1;
  if v_egasi is null then
    select h.kompaniya_id into v_egasi
      from public.t2_tomon_murojaat_hujjat h
      join public.t2_tomon_murojaat m on m.id = h.murojaat_id and m.holat <> 'bekor'
      join public.t2_tomon_aloqa a on a.id = m.aloqa_id and a.holat = 'faol'
     where h.document_id = p_document_id
       and exists (select 1 from public.t2_azolik z where z.foydalanuvchi_id = p_actor_id and z.holat = 'faol' and z.kompaniya_id in (m.beruvchi_kompaniya_id, m.ijrochi_kompaniya_id))
     order by h.id desc limit 1;
  end if;
  if v_egasi is null then
    select q.taqdim_etuvchi_kompaniya_id into v_egasi
      from public.t2_tomon_taqdim q join public.t2_tomon_aloqa a on a.id = q.aloqa_id and a.holat = 'faol'
     where q.manba_jadval = 't2_aosr' and q.holat in ('yuborilgan','ko_rilmoqda','qabul','tuzatish')
       and exists (select 1 from public.t2_azolik z where z.foydalanuvchi_id = p_actor_id and z.kompaniya_id = q.qabul_qiluvchi_kompaniya_id and z.holat = 'faol')
       and (exists (select 1 from public.t2_aosr_foto f where f.aosr_id = q.manba_id and f.document_id = p_document_id)
            or exists (select 1 from public.t2_lab_protokol_bog pb join public.t2_lab_protokol p on p.id = pb.protokol_id and p.holat <> 'bekor'
                        where pb.aosr_id = q.manba_id and p.fayl_document_id = p_document_id::text))
     order by q.id desc limit 1;
  end if;
  if v_egasi is null then return jsonb_build_object('ok', false, 'code', 'DOCUMENT_FORBIDDEN'); end if;
  select * into d from public.t2_document_registry where id = p_document_id and kompaniya_id = v_egasi;
  if not found then return jsonb_build_object('ok', false, 'code', 'DOCUMENT_NOT_FOUND'); end if;
  if d.canonical_storage_status is distinct from 'stored' or d.r2_key is null then return jsonb_build_object('ok', false, 'code', 'CANONICAL_BINARY_MISSING'); end if;
  return jsonb_build_object('ok', true, 'document_id', d.id, 'r2_key', d.r2_key, 'blob_key', coalesce(d.blob_key, d.r2_key), 'mime_type', d.mime_type, 'original_filename', d.original_filename, 'size_bytes', d.size_bytes, 'sha256', d.sha256);
end $$;

-- 6. Tekshiruvni yozish / yakunlash (+ avtomatik predpisaniya)
-- p_bandlar: [{kod, nom, natija: mos|mos_emas|yoq, izoh, muhimlik, document_ids:[...]}]. p_id bo'sh = yangi qoralama.
create or replace function public.t2_nazorat_tekshiruv_yoz_v1(
  p_actor_id bigint, p_kompaniya_id bigint, p_operation_id uuid, p_id bigint, p_aloqa_id bigint, p_obyekt_id bigint,
  p_sana date, p_ish_turi text, p_joy text, p_bandlar jsonb, p_izoh text, p_yakunla boolean, p_muddat_kun integer)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare
  a public.t2_tomon_aloqa; ob public.t2_obyekt; t public.t2_tekshiruv; m public.t2_tomon_murojaat;
  v_id bigint; v_ij bigint; v_docs bigint[]; v_n integer; v_band jsonb; v_res jsonb; v_pred bigint[] := '{}'; v_mid bigint;
  v_bad integer := 0; v_ok integer := 0; v_kun integer; v_muh text; v_bdocs bigint[];
begin
  perform public._t2_tomon_azo(p_actor_id, p_kompaniya_id, 'murojaat');
  if p_bandlar is null or jsonb_typeof(p_bandlar) <> 'array' or jsonb_array_length(p_bandlar) > 80 then
    return jsonb_build_object('ok', false, 'code', 'BANDLAR', 'error', 'Tekshiruv bandlari ro''yxat bo''lishi kerak (ko''pi bilan 80)');
  end if;
  if length(btrim(coalesce(p_ish_turi, ''))) < 2 then return jsonb_build_object('ok', false, 'code', 'ISH_TURI', 'error', 'Ish turini tanlang'); end if;
  for v_band in select e from jsonb_array_elements(p_bandlar) e loop
    if jsonb_typeof(v_band) <> 'object' or length(btrim(coalesce(v_band->>'nom', ''))) < 2 or length(btrim(coalesce(v_band->>'kod', ''))) < 1
       or coalesce(v_band->>'natija', '') not in ('mos','mos_emas','yoq')
       or (v_band ? 'document_ids' and jsonb_typeof(v_band->'document_ids') <> 'array')
       or coalesce(v_band->>'muhimlik', 'yuqori') not in ('past','oddiy','yuqori','kritik') then
      return jsonb_build_object('ok', false, 'code', 'BAND_NOTOGRI', 'error', 'Band noto''g''ri: kod, nom, natija (mos | mos_emas | yoq) kerak');
    end if;
  end loop;
  begin
    select coalesce(array_agg(distinct d::bigint), '{}') into v_docs
      from jsonb_array_elements(p_bandlar) e, jsonb_array_elements_text(coalesce(e->'document_ids', '[]'::jsonb)) d;
  exception when invalid_text_representation then
    return jsonb_build_object('ok', false, 'code', 'FOTO_NOTOGRI', 'error', 'Foto identifikatori noto''g''ri');
  end;
  if coalesce(array_length(v_docs, 1), 0) > 200 then return jsonb_build_object('ok', false, 'code', 'FOTO_KOP', 'error', 'Bitta tekshiruvda ko''pi bilan 200 ta foto'); end if;
  if coalesce(array_length(v_docs, 1), 0) > 0 then
    select count(*) into v_n from public.t2_document_registry d where d.id = any (v_docs) and d.kompaniya_id = p_kompaniya_id and d.canonical_storage_status = 'stored';
    if v_n <> array_length(v_docs, 1) then
      return jsonb_build_object('ok', false, 'code', 'FOTO_BEGONA', 'error', 'Foto sizning kompaniyangizniki emas yoki hali saqlanmagan');
    end if;
  end if;

  select * into ob from public.t2_obyekt where id = p_obyekt_id and holat = 'faol';
  if not found then return jsonb_build_object('ok', false, 'code', 'OBYEKT_YOQ', 'error', 'Obyekt topilmadi'); end if;
  if ob.kompaniya_id <> p_kompaniya_id then
    select * into a from public.t2_tomon_aloqa where id = p_aloqa_id;
    if not found or (a.taklif_kompaniya_id <> p_kompaniya_id and a.qabul_kompaniya_id is distinct from p_kompaniya_id) or a.holat <> 'faol' then
      return jsonb_build_object('ok', false, 'code', 'ALOQA_YOQ', 'error', 'Faol aloqa topilmadi');
    end if;
    v_ij := public._t2_tomon_qarshi(a, p_kompaniya_id);
    if v_ij is distinct from ob.kompaniya_id or not public.t2_tomon_ruxsat_bor(p_kompaniya_id, v_ij, 'obyekt_holat', 'korish', p_obyekt_id) then
      return jsonb_build_object('ok', false, 'code', 'OBYEKT_YOPIQ', 'error', 'Bu obyekt sizga ochilmagan');
    end if;
  end if;

  if p_id is null then
    if p_operation_id is null then return jsonb_build_object('ok', false, 'code', 'OPERATION', 'error', 'operation_id majburiy'); end if;
    select * into t from public.t2_tekshiruv where kompaniya_id = p_kompaniya_id and operation_id = p_operation_id;
    if found then v_id := t.id;
    else
      insert into public.t2_tekshiruv (kompaniya_id, aloqa_id, obyekt_id, sana, ish_turi, joy, bandlar, izoh, yaratdi_actor_id, operation_id)
      values (p_kompaniya_id, case when ob.kompaniya_id <> p_kompaniya_id then p_aloqa_id end, p_obyekt_id, coalesce(p_sana, current_date), btrim(p_ish_turi),
              nullif(btrim(coalesce(p_joy, '')), ''), p_bandlar, nullif(btrim(coalesce(p_izoh, '')), ''), p_actor_id, p_operation_id)
      returning id into v_id;
    end if;
  else
    v_id := p_id;
  end if;
  select * into t from public.t2_tekshiruv where id = v_id and kompaniya_id = p_kompaniya_id for update;
  if not found then return jsonb_build_object('ok', false, 'code', 'TOPILMADI', 'error', 'Tekshiruv topilmadi'); end if;
  if t.holat = 'yakunlandi' then
    return jsonb_build_object('ok', true, 'id', t.id, 'holat', t.holat, 'natija', t.natija, 'qayta', true,
      'predpisaniyalar', (select coalesce(jsonb_agg(x.id order by x.id), '[]'::jsonb) from public.t2_tomon_murojaat x where x.tekshiruv_id = t.id));
  end if;
  if t.holat <> 'qoralama' then return jsonb_build_object('ok', false, 'code', 'HOLAT', 'error', 'Bekor qilingan tekshiruv o''zgartirilmaydi'); end if;
  if p_id is not null then
    update public.t2_tekshiruv set sana = coalesce(p_sana, sana), ish_turi = btrim(p_ish_turi), joy = nullif(btrim(coalesce(p_joy, '')), ''),
           bandlar = p_bandlar, izoh = nullif(btrim(coalesce(p_izoh, '')), ''), versiya = versiya + 1, yangilandi = now()
     where id = t.id;
  end if;
  if not coalesce(p_yakunla, false) then
    return jsonb_build_object('ok', true, 'id', v_id, 'holat', 'qoralama');
  end if;

  -- Yakunlash: har nomuvofiq band izoh + foto bilan; hech bo'lmasa bitta band tekshirilgan bo'lishi shart.
  for v_band in select e from jsonb_array_elements(p_bandlar) e loop
    if v_band->>'natija' = 'mos_emas' then
      v_bad := v_bad + 1;
      if length(btrim(coalesce(v_band->>'izoh', ''))) < 3 then
        return jsonb_build_object('ok', false, 'code', 'IZOH_KERAK', 'error', 'Nomuvofiq band uchun nima noto''g''riligini yozing: ' || (v_band->>'nom'));
      end if;
      if jsonb_array_length(coalesce(v_band->'document_ids', '[]'::jsonb)) = 0 then
        return jsonb_build_object('ok', false, 'code', 'FOTO_KERAK', 'error', 'Nomuvofiq band uchun foto kerak: ' || (v_band->>'nom'));
      end if;
    elsif v_band->>'natija' = 'mos' then
      v_ok := v_ok + 1;
    end if;
  end loop;
  if v_bad + v_ok = 0 then return jsonb_build_object('ok', false, 'code', 'BOSH', 'error', 'Hech bo''lmasa bitta bandni tekshiring'); end if;

  if v_bad > 0 and ob.kompaniya_id <> p_kompaniya_id then
    for v_band in select e from jsonb_array_elements(p_bandlar) e where e->>'natija' = 'mos_emas' loop
      v_muh := coalesce(v_band->>'muhimlik', 'yuqori');
      v_kun := least(greatest(coalesce(p_muddat_kun, case when v_muh = 'kritik' then 3 else 7 end), 1), 60);
      v_res := public.t2_tomon_murojaat_yarat_v1(p_actor_id, p_kompaniya_id, p_aloqa_id, 'predpisaniya',
                 left(btrim(p_ish_turi) || ' - ' || btrim(v_band->>'nom'), 200), btrim(v_band->>'izoh'), v_muh, current_date + v_kun, p_obyekt_id,
                 nullif(btrim(coalesce(p_joy, '')), ''), md5(coalesce(p_operation_id::text, v_id::text) || ':' || (v_band->>'kod'))::uuid);
      if not coalesce((v_res->>'ok')::boolean, false) then
        raise exception 'PREDPISANIYA_XATO: %', coalesce(v_res->>'error', 'predpisaniya yaratilmadi') using errcode = '22023';
      end if;
      v_mid := (v_res->>'id')::bigint;
      update public.t2_tomon_murojaat set tekshiruv_id = v_id, band_kod = left(v_band->>'kod', 60) where id = v_mid returning * into m;
      select coalesce(array_agg(d::bigint), '{}') into v_bdocs from jsonb_array_elements_text(coalesce(v_band->'document_ids', '[]'::jsonb)) d;
      perform public._t2_tomon_dalil_biriktir(m, p_kompaniya_id, p_actor_id, v_bdocs);
      v_pred := v_pred || v_mid;
    end loop;
  end if;
  update public.t2_tekshiruv set holat = 'yakunlandi', natija = case when v_bad > 0 then 'mos_emas' else 'mos' end,
         yakunlandi_vaqti = now(), versiya = versiya + 1, yangilandi = now() where id = v_id;
  return jsonb_build_object('ok', true, 'id', v_id, 'holat', 'yakunlandi', 'natija', case when v_bad > 0 then 'mos_emas' else 'mos' end,
    'predpisaniyalar', to_jsonb(v_pred), 'predpisaniya_yaratilmadi', v_bad > 0 and ob.kompaniya_id = p_kompaniya_id);
end $$;

-- 7. Tekshiruvlar jurnali (kun/obyekt bo'yicha) - kunlik jurnal eksporti uchun bandlar bilan
create or replace function public.t2_nazorat_tekshiruvlar_v1(p_actor_id bigint, p_kompaniya_id bigint, p_dan date, p_gacha date, p_obyekt_id bigint, p_limit integer)
returns jsonb language plpgsql security definer set search_path = public, pg_temp as $$
declare v jsonb; v_lim integer := least(greatest(coalesce(p_limit, 200), 1), 500);
begin
  perform public._t2_tomon_azo(p_actor_id, p_kompaniya_id, 'korish');
  select coalesce(jsonb_agg(x order by (x->>'sana') desc, (x->>'id')::bigint desc), '[]'::jsonb) into v from (
    select jsonb_build_object('id', t.id, 'sana', t.sana, 'obyekt_id', t.obyekt_id, 'obyekt_nom', (select o.nom from public.t2_obyekt o where o.id = t.obyekt_id),
             'aloqa_id', t.aloqa_id, 'ish_turi', t.ish_turi, 'joy', t.joy, 'holat', t.holat, 'natija', t.natija, 'izoh', t.izoh, 'bandlar', t.bandlar,
             'predpisaniya_soni', (select count(*) from public.t2_tomon_murojaat m where m.tekshiruv_id = t.id),
             'yaratildi', t.yaratildi, 'yakunlandi_vaqti', t.yakunlandi_vaqti) x
      from public.t2_tekshiruv t
     where t.kompaniya_id = p_kompaniya_id and t.holat <> 'bekor'
