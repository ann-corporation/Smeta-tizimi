-- Yangi jadvallar (kichik): t2_tekshiruv (tashrif + checklist jsonb), t2_aosr_foto (АОСР foto havolasi). Fayl baytlari R2 da (t2_document_registry).
-- DB hajmi: t2_tekshiruv ~1.5 KB/tashrif (checklist jsonb, foto faqat ID) -> 1 inspektor ~25 tashrif/oy ~ 40 KB/oy; t2_aosr_foto ~100 B/qator. Jami < 1 MB/oy.
