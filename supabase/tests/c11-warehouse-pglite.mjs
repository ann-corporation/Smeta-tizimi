import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

// Synthetic-only contract runner. Install PGlite separately, e.g.
//   npm install --prefix C:/Temp/c11-sql-runtime @electric-sql/pglite@0.5.12
// Then set C11_PGLITE_DIR to that package directory before running this file.
// The mock guards below are not production authorization parity.
const pgliteDir = process.env.C11_PGLITE_DIR;
const pgliteModule = pgliteDir
  ? pathToFileURL(resolve(pgliteDir, 'dist/index.js')).href
  : '@electric-sql/pglite';
const { PGlite } = await import(pgliteModule);

const migration = await readFile(new URL('../migrations/20261113810000_c11_warehouse_receipt_v1.sql', import.meta.url), 'utf8');
const acceptance = await readFile(new URL('./c11_warehouse_receipt_v1.sql', import.meta.url), 'utf8');
const rollback = await readFile(new URL('../migrations/20261113810000_c11_warehouse_receipt_v1.rollback.sql', import.meta.url), 'utf8');
const db = new PGlite();

try {
  await db.exec(`
    CREATE ROLE anon;
    CREATE ROLE authenticated;
    CREATE ROLE service_role;
    CREATE TABLE public.t2_kompaniya (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nom text NOT NULL,
      kod text NOT NULL UNIQUE,
      faol boolean NOT NULL DEFAULT true
    );
    CREATE TABLE public.t2_foydalanuvchi (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      login text NOT NULL UNIQUE,
      holat text NOT NULL DEFAULT 'faol'
    );
    CREATE TABLE public.t2_azolik (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      foydalanuvchi_id bigint NOT NULL REFERENCES public.t2_foydalanuvchi(id),
      kompaniya_id bigint NOT NULL REFERENCES public.t2_kompaniya(id),
      rol text NOT NULL,
      holat text NOT NULL DEFAULT 'faol' CHECK (holat IN ('faol','bekor'))
    );
    CREATE TABLE public.t2_sklad_harakat (
      id bigserial PRIMARY KEY,
      kompaniya_id bigint NOT NULL,
      obyekt_id bigint NOT NULL,
      operatsiya text NOT NULL,
      turi text,
      sana date,
      nomi text,
      birligi text,
      obyomi numeric,
      postavshik text,
      qabul_qiluvchi text,
      qabul_turi text,
      izoh text,
      holat text,
      operation_id uuid,
      manba text,
      kim text,
      yaratildi timestamptz NOT NULL DEFAULT now()
    );
    CREATE TABLE public.t2_sklad_mustaqil (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      kompaniya_id bigint NOT NULL REFERENCES public.t2_kompaniya(id),
      nomi text NOT NULL,
      holat text NOT NULL DEFAULT 'faol' CHECK (holat IN ('faol','bekor'))
    );
    CREATE TABLE public.t2_document_registry (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      kompaniya_id bigint NOT NULL REFERENCES public.t2_kompaniya(id),
      document_type text NOT NULL,
      provider text,
      status text NOT NULL CHECK (status IN ('pending','active','superseded','deleted','failed','replica_missing')),
      canonical_storage_status text NOT NULL DEFAULT 'pending' CHECK (canonical_storage_status IN ('pending','reserved','stored','failed')),
      r2_bucket text NOT NULL DEFAULT 'canonical',
      r2_key text,
      sha256 text,
      sha256_verified boolean NOT NULL DEFAULT false,
      hash_source text NOT NULL DEFAULT 'server' CHECK (hash_source IN ('server','client'))
    );
    CREATE TABLE public.t2_kontragent (id bigint PRIMARY KEY, kompaniya_id bigint NOT NULL, nom text NOT NULL);
    CREATE TABLE public.t2_erp_taminot (id bigint PRIMARY KEY, kompaniya_id bigint NOT NULL);
    CREATE FUNCTION public.t2_actor_kompaniya_azo_tekshir(p_kompaniya_id bigint, p_actor_id bigint)
    RETURNS text LANGUAGE plpgsql AS $$
    DECLARE v_rol text;
    BEGIN
      IF NOT EXISTS (
        SELECT 1 FROM public.t2_foydalanuvchi u
        JOIN public.t2_azolik a ON a.foydalanuvchi_id = u.id
        JOIN public.t2_kompaniya c ON c.id = a.kompaniya_id
        WHERE u.id = p_actor_id AND u.holat = 'faol'
          AND a.kompaniya_id = p_kompaniya_id AND a.holat = 'faol' AND c.faol
      ) THEN
        RAISE EXCEPTION 'synthetic tenant actor rejected' USING ERRCODE = '42501';
      END IF;
      SELECT rol INTO v_rol FROM public.t2_azolik
       WHERE foydalanuvchi_id = p_actor_id AND kompaniya_id = p_kompaniya_id AND holat = 'faol';
      RETURN v_rol;
    END $$;
    CREATE FUNCTION public.t2_require_permission_v2(p_kompaniya_id bigint, p_actor_id bigint, p_permission text)
    RETURNS void LANGUAGE plpgsql AS $$
    BEGIN
      IF public.t2_actor_kompaniya_azo_tekshir(p_kompaniya_id, p_actor_id) <> 'admin'
         OR p_permission NOT IN ('document.read','document.write') THEN
        RAISE EXCEPTION 'synthetic permission rejected' USING ERRCODE = '42501';
      END IF;
    END $$;
    CREATE FUNCTION public.t2_audit_yoz(bigint,text,text,bigint,text,text,text)
    RETURNS void LANGUAGE sql AS $$ SELECT NULL::void $$;
  `);

  await db.exec(migration);
  const legacyInserted = await db.query(`
    INSERT INTO public.t2_sklad_harakat
      (kompaniya_id, obyekt_id, operatsiya, nomi, holat, manba)
    VALUES (910001, 910002, 'prixod', 'synthetic legacy before', 'faol', 'legacy_harness_only')
    RETURNING id
  `);
  const legacyId = legacyInserted.rows[0]?.id;
  if (!legacyId) throw new Error('harness-only legacy row insert failed');
  const legacyUpdated = await db.query(`
    UPDATE public.t2_sklad_harakat SET nomi = 'synthetic legacy after'
     WHERE id = $1 RETURNING id, nomi
  `, [legacyId]);
  if (legacyUpdated.rows.length !== 1 || legacyUpdated.rows[0].nomi !== 'synthetic legacy after') {
    throw new Error('legacy object-linked UPDATE did not return and retain the changed row');
  }
  const legacyDeleted = await db.query(`
    DELETE FROM public.t2_sklad_harakat WHERE id = $1 RETURNING id
  `, [legacyId]);
  if (legacyDeleted.rows.length !== 1) throw new Error('legacy object-linked DELETE did not remove the row');

  for (let run = 1; run <= 2; run += 1) {
    await db.exec(acceptance);
    const fixtureResidue = await db.query(`
      SELECT
        (SELECT count(*) FROM public.t2_kompaniya WHERE kod LIKE 'C11A-%' OR kod LIKE 'C11B-%') AS companies,
        (SELECT count(*) FROM public.t2_foydalanuvchi
          WHERE login LIKE 'c11-admin-%' OR login LIKE 'c11-outsider-%' OR login LIKE 'c11-denied-%') AS users,
        (SELECT count(*) FROM public.t2_azolik a JOIN public.t2_kompaniya c ON c.id = a.kompaniya_id
          WHERE c.kod LIKE 'C11A-%' OR c.kod LIKE 'C11B-%') AS memberships,
        (SELECT count(*) FROM public.t2_sklad_mustaqil w JOIN public.t2_kompaniya c ON c.id = w.kompaniya_id
          WHERE c.kod LIKE 'C11A-%' OR c.kod LIKE 'C11B-%') AS warehouses,
        (SELECT count(*) FROM public.t2_document_registry d JOIN public.t2_kompaniya c ON c.id = d.kompaniya_id
          WHERE c.kod LIKE 'C11A-%' OR c.kod LIKE 'C11B-%') AS documents,
        (SELECT count(*) FROM public.t2_sklad_harakat
          WHERE manba IN ('c11_warehouse_receipt_v1','c11_warehouse_storno_v1')) AS movements
    `).then((result) => result.rows[0]);
    if (Object.values(fixtureResidue).some((count) => Number(count) !== 0)) {
      throw new Error(`acceptance run ${run} left synthetic fixtures behind: ${JSON.stringify(fixtureResidue)}`);
    }
  }
  await db.exec(rollback);

  const readRollbackState = async () => (await db.query(`
    SELECT
      (SELECT count(*) FROM information_schema.columns
        WHERE table_schema='public' AND table_name='t2_sklad_harakat'
          AND column_name LIKE 'c11_%') AS c11_columns_left,
      (SELECT is_nullable FROM information_schema.columns
        WHERE table_schema='public' AND table_name='t2_sklad_harakat'
          AND column_name='obyekt_id') AS object_id_nullable,
      to_regclass('public.t2_sklad_ombor_qoldiq_v1') IS NULL AS view_removed,
      to_regprocedure('public.t2_sklad_c11_append_only_guard_v1()') IS NULL AS guard_removed,
      to_regprocedure('public.t2_sklad_kirim_royxat_v1(bigint,bigint,bigint,jsonb,integer,integer)') IS NULL AS list_rpc_removed,
      to_regprocedure('public.t2_sklad_c11_qidiruv_kaliti_v1(text)') IS NULL AS search_helper_removed
  `)).rows[0];
  const assertRollbackState = (state, label) => {
    if (Number(state.c11_columns_left) !== 0 || state.object_id_nullable !== 'NO'
        || !state.view_removed || !state.guard_removed
        || !state.list_rpc_removed || !state.search_helper_removed) {
      throw new Error(label + ' postconditions failed: ' + JSON.stringify(state));
    }
  };
  const result = await readRollbackState();
  assertRollbackState(result, 'rollback');

  await db.exec(migration);
  await db.exec(rollback);
  const reapplyRollback = await readRollbackState();
  assertRollbackState(reapplyRollback, 'reapply-and-rollback');

  console.log(JSON.stringify({
    status: 'PASS_SYNTHETIC_SQL_ONLY',
    migration: 'executed_twice_with_rollback_between',
    acceptance: 'executed_twice_with_assertions_and_zero_fixture_residue_each_time',
    rollback: 'executed_twice_and_postconditions_verified_each_time',
    auth: 'explicit_mock_guards_not_production_parity',
    legacyCrud: 'passed_harness_only_without_production_object_fk_parity',
    concurrency: 'not_proven_single_connection',
    postRollback: { first: result, reapply: reapplyRollback }
  }, null, 2));
} catch (error) {
  console.error(JSON.stringify({
    status: 'FAIL_SYNTHETIC_SQL',
    name: error?.name,
    message: error?.message,
    code: error?.code,
    detail: error?.detail,
    hint: error?.hint,
    where: error?.where,
    position: error?.position,
    stack: error?.stack
  }, null, 2));
  process.exitCode = 1;
} finally {
  await db.close();
}
