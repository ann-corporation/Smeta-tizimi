#!/usr/bin/env node
/**
 * design/tokens.json  ->  sayt CSS + TS konstantalari + Kotlin DesignTokens.kt  (yagona dizayn manbasi).
 *   node scripts/gen-design-tokens.mjs           yozadi
 *   node scripts/gen-design-tokens.mjs --check   eskirgan bo'lsa 1 bilan chiqadi (CI)
 * Qo'lda tahrir QILINMAYDI: o'zgarish design/tokens.json da, so'ng shu skript.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ildiz = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const T = JSON.parse(readFileSync(resolve(ildiz, 'design/tokens.json'), 'utf8'));
for (const k of Object.keys(T.status)) if (k.startsWith('$')) delete T.status[k];
delete T.icons['$comment']; delete T.format['$comment']; delete T.telegram['$comment'];

export const MAQSAD = {
  css: 'frontend/src/dizayn/tokens.generated.css',
  ts: 'frontend/src/dizayn/tokens.generated.ts',
  kt: 'android-native/ui-common/src/commonMain/kotlin/uz/anncorp/smeta/core/ui/DesignTokens.kt',
};

const BELGI = '// GENERATED by scripts/gen-design-tokens.mjs from design/tokens.json - do not edit by hand.';
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const kt = (hex) => { // #rrggbb[aa] -> 0xAARRGGBB
  const h = hex.slice(1); const a = h.length === 8 ? h.slice(6) : 'ff';
  return '0x' + (a + h.slice(0, 6)).toUpperCase();
};
const SOZ = (s) => s.replace(/[A-Z]/g, (c) => '_' + c).toUpperCase();

function css() {
  const blok = (sel, c, el, qoshimcha) => {
    const q = Object.entries(c).map(([k, v]) => `  --${k}: ${v};`);
    q.push(`  --shadow-pop: ${el.pop};`, `  --shadow-raise: ${el.raise};`);
    return `${sel} {\n${q.join('\n')}${qoshimcha ?? ''}\n}\n`;
  };
  const umumiy = [
    ...Object.entries(T.spacing).map(([k, v]) => `  --space-${k}: ${v}px;`),
    ...Object.entries(T.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`),
    ...Object.entries(T.control).map(([k, v]) => `  --control-${k}: ${v}px;`),
    ...Object.entries(T.row).map(([k, v]) => `  --row-${k}: ${v}px;`),
    ...Object.entries(T.sidebar).map(([k, v]) => `  --sidebar-${k}: ${v}px;`),
    `  --brand-navy: ${T.brand.navy};`, `  --brand-gold: ${T.brand.gold};`,
    ...Object.entries(T.typography).flatMap(([k, v]) => {
      const n = k.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
      return [`  --fs-${n}: ${v.size}px;`, `  --lh-${n}: ${v.line}px;`, `  --fw-${n}: ${v.weight};`];
    }),
    ...Object.entries(T.status).flatMap(([guruh, m]) => Object.entries(m).map(([k, v]) => `  --st-${guruh}-${k}: var(--${v.tone === 'neutral' ? 'text-dim' : v.tone === 'frozen' ? 'info' : v.tone});`)),
  ].join('\n');
  return `/* ${BELGI.slice(3)} */\n/* Yagona dizayn manbasi: design/tokens.json. firuza.css shu fayldan KEYIN ulanadi va faqat qolgan (sayt-ichki) qatlamni beradi. */\n\n` +
    blok(':root,\n[data-mavzu="tun"]', T.color.dark, T.elevation.dark, '\n' + umumiy + '\n  color-scheme: dark;') + '\n' +
    blok('[data-mavzu="ganch"]', T.color.light, T.elevation.light, '\n  color-scheme: light;');
}

function ts() {
  const j = (o) => JSON.stringify(o, null, 2);
  return `${BELGI}\n/* eslint-disable */\nexport const TOKENS_RANG = ${j(T.color)} as const;\nexport const TOKENS_TIPOGRAFIYA = ${j(T.typography)} as const;\n` +
    `export const TOKENS_HOLAT = ${j(T.status)} as const;\nexport type HolatTon = 'neutral' | 'ok' | 'warn' | 'danger' | 'info' | 'accent' | 'frozen';\n` +
    `export const TOKENS_NAV = ${j(T.nav)} as const;\nexport const TOKENS_IKONKALAR = ${j(T.icons.names)} as const;\n` +
    `export const TOKENS_FORMAT = ${j(T.format)} as const;\nexport const TOKENS_TELEGRAM = ${j(T.telegram)} as const;\n`;
}

function ktFayl() {
  const pal = (c) => `QuraiPalette(
        bg = ${kt(c.bg)}, surface = ${kt(c.surface)}, surface2 = ${kt(c['surface-2'])}, surface3 = ${kt(c['surface-3'])}, border = ${kt(c.border)}, borderStrong = ${kt(c['border-strong'])},
        text = ${kt(c.text)}, textDim = ${kt(c['text-dim'])}, textMute = ${kt(c['text-mute'])},
        accent = ${kt(c.accent)}, accentText = ${kt(c['accent-text'])}, onAccent = ${kt(c['on-accent'])}, accentSoft = ${kt(c['accent-soft'])},
        info = ${kt(c.info)}, ok = ${kt(c.ok)}, warn = ${kt(c.warn)}, danger = ${kt(c.danger)}, dangerSoft = ${kt(c['danger-soft'])},
        okSoft = ${kt(c['ok-soft'])}, warnSoft = ${kt(c['warn-soft'])}, infoSoft = ${kt(c['info-soft'])},
        katChel = ${kt(c['kat-chel'])}, katMash = ${kt(c['kat-mash'])}, katMat = ${kt(c['kat-mat'])}, katOb = ${kt(c['kat-ob'])},
    )`;
  const consts = (obj, pre) => Object.entries(obj).map(([k, v]) => `    const val ${pre}${SOZ(k)} = ${v}`).join('\n');
  const typo = Object.entries(T.typography).map(([k, v]) => `    val ${SOZ(k)} = DesignTextSpec(${v.size}, ${v.line}, ${v.weight})`).join('\n');
  const q = (s) => JSON.stringify(s).replace(/\$/g, '\\$').replace(/[^\x20-\x7e]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
  const holat = Object.entries(T.status).map(([g, m]) =>
    `        ${q(g)} to mapOf(\n` + Object.entries(m).map(([k, v]) => `            ${q(k)} to DesignStatus(${q(v.label)}, ${q(v.tone)})`).join(',\n') + ',\n        )').join(',\n');
  const nav = T.nav.map((s) => `        DesignNavSection(${q(s.id)}, ${q(s.title)}, ${q(s.icon)}, listOf(${s.items.map(([id, t]) => `DesignNavItem(${q(id)}, ${q(t)})`).join(', ')}))`).join(',\n');
  return `${BELGI}
package uz.anncorp.smeta.core.ui

/** Source of truth: design/tokens.json (site CSS, Android and Windows read the SAME values). QuraiTokens / QTheme delegate here. */
data class DesignTextSpec(val size: Int, val line: Int, val weight: Int)
data class DesignStatus(val label: String, val tone: String)
data class DesignNavItem(val id: String, val title: String)
data class DesignNavSection(val id: String, val title: String, val icon: String, val items: List<DesignNavItem>)

object DesignTokens {
    val dark = ${pal(T.color.dark)}

    val light = ${pal(T.color.light)}

    const val BRAND_NAVY = ${kt(T.brand.navy)}
    const val BRAND_GOLD = ${kt(T.brand.gold)}

${consts(Object.fromEntries(Object.entries(T.spacing).map(([k, v]) => [k, v])), 'SPACE_')}
${consts(T.radius, 'RADIUS_')}
${consts(T.control, 'CONTROL_')}
${consts(T.row, 'ROW_')}
${consts(T.sidebar, 'SIDEBAR_')}
${consts(T.breakpoint, 'BREAKPOINT_')}
    const val FONT_SANS = ${q(T.font.sans)}
    const val FONT_MONO = ${q(T.font.mono)}

${typo}

    /** Status badges by domain (f2 / fakt / zayavka): label + tone (neutral, ok, warn, danger, info, accent, frozen). */
    val status: Map<String, Map<String, DesignStatus>> = mapOf(
${holat},
    )

    val nav: List<DesignNavSection> = listOf(
${nav},
    )

    const val GROUP_SEPARATOR = ${q(T.format.groupSeparator)}
    const val DECIMAL_SEPARATOR = ${q(T.format.decimalSeparator)}
    const val UNKNOWN = ${q(T.format.unknown)}
}
`;
}

const chiqish = { [MAQSAD.css]: css(), [MAQSAD.ts]: ts(), [MAQSAD.kt]: ktFayl() };
const tekshir = process.argv.includes('--check');
let eskirgan = 0;
for (const [yol, matn] of Object.entries(chiqish)) {
  const to = resolve(ildiz, yol);
  const hozir = existsSync(to) ? readFileSync(to, 'utf8').replace(/\r\n/g, '\n') : null;
  if (tekshir) { if (hozir !== matn) { console.error(`ESKIRGAN: ${yol} - 'node scripts/gen-design-tokens.mjs' ni yurgizing`); eskirgan++; } continue; }
  mkdirSync(dirname(to), { recursive: true });
  if (hozir !== matn) writeFileSync(to, matn);
}
if (tekshir) process.exit(eskirgan ? 1 : 0);
console.log('design tokens: yozildi');
